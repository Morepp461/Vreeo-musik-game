-- Vreeo Music & Games Supabase schema
create table if not exists music_history (
 id bigint generated by default as identity primary key,
 user_id bigint not null,
 title text not null,
 source_url text,
 played_at timestamptz default now()
);
create index if not exists music_history_user_played_idx on music_history(user_id,played_at desc);

create table if not exists favorites (
 user_id bigint not null,
 title text not null,
 source_url text not null,
 created_at timestamptz default now(),
 primary key(user_id,source_url)
);

create table if not exists playlists (
 id bigint generated by default as identity primary key,
 user_id bigint not null,
 name text not null,
 created_at timestamptz default now(),
 unique(user_id,name)
);

create table if not exists playlist_tracks (
 playlist_id bigint references playlists(id) on delete cascade,
 position integer not null,
 title text not null,
 source_url text not null,
 primary key(playlist_id,position)
);
create index if not exists playlist_tracks_playlist_idx on playlist_tracks(playlist_id,position);

create table if not exists users (
 user_id bigint primary key,
 display_name text,
 created_at timestamptz default now(),
 last_seen timestamptz default now()
);
create table if not exists economy (
 user_id bigint primary key references users(user_id) on delete cascade,
 balance bigint not null default 0,
 bank bigint not null default 0
);
create table if not exists transactions (
 id bigint generated by default as identity primary key,
 user_id bigint not null,
 amount bigint not null,
 kind text not null,
 metadata jsonb default '{}'::jsonb,
 created_at timestamptz default now()
);
create table if not exists inventory (
 user_id bigint not null,
 item_key text not null,
 quantity integer not null default 0,
 primary key(user_id,item_key)
);
create table if not exists game_stats (
 user_id bigint primary key references users(user_id) on delete cascade,
 wins integer not null default 0,
 losses integer not null default 0,
 draws integer not null default 0,
 games integer not null default 0
);
create table if not exists achievements (
 key text primary key,
 name text not null,
 description text not null
);
create table if not exists user_achievements (
 user_id bigint not null,
 achievement_key text references achievements(key) on delete cascade,
 unlocked_at timestamptz default now(),
 primary key(user_id,achievement_key)
);
create table if not exists daily_rewards (
 user_id bigint primary key,
 streak integer not null default 0,
 last_claimed date
);
create table if not exists bot_settings (
 key text primary key,
 value jsonb not null default '{}'::jsonb,
 updated_at timestamptz default now()
);

