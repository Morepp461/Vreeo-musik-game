-- WNI SIMULATOR Batch 1: Player Core
create table if not exists game_characters (
  id bigint generated by default as identity primary key,
  discord_user_id text not null unique,
  guild_id text not null,
  name text not null check (char_length(name) between 1 and 32),
  gender text not null check (gender in ('Laki-laki','Perempuan')),
  birth_date date not null,
  background text not null default 'Umum',
  province text not null default 'Jawa Timur',
  city text not null default 'Malang',
  district text,
  village text,
  status text not null default 'active' check (status in ('active','dead','retired')),
  health smallint not null default 100 check (health between 0 and 100),
  happiness smallint not null default 70 check (happiness between 0 and 100),
  stress smallint not null default 20 check (stress between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists game_characters_guild_idx on game_characters(guild_id);
create index if not exists game_characters_status_idx on game_characters(status);

create table if not exists game_wallets (
  id bigint generated by default as identity primary key,
  character_id bigint not null unique references game_characters(id) on delete cascade,
  cash bigint not null default 0 check (cash >= 0),
  bank bigint not null default 0 check (bank >= 0),
  debt bigint not null default 0 check (debt >= 0),
  currency text not null default 'IDR',
  updated_at timestamptz not null default now()
);
create table if not exists game_transactions (
  id bigint generated by default as identity primary key,
  wallet_id bigint not null references game_wallets(id) on delete cascade,
  account_type text not null check (account_type in ('cash','bank','debt')),
  amount bigint not null,
  balance_after bigint not null check (balance_after >= 0),
  transaction_type text not null,
  description text not null,
  reference_key text,
  created_at timestamptz not null default now()
);
create index if not exists game_transactions_wallet_time_idx on game_transactions(wallet_id, created_at desc);
create table if not exists game_inventory (
  id bigint generated by default as identity primary key,
  character_id bigint not null references game_characters(id) on delete cascade,
  item_key text not null,
  item_name text not null,
  quantity bigint not null default 1 check (quantity >= 0),
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique(character_id,item_key)
);
create table if not exists game_asset_templates (
  id bigint generated by default as identity primary key,
  asset_key text not null unique,
  category text not null,
  name text not null,
  base_price bigint not null check (base_price >= 0),
