 mayor_character_id bigint references public.game_characters(id) on delete set null,
 budget bigint not null default 0 check (budget >= 0),
 approval numeric(5,2) not null default 60 check (approval between 0 and 100),
 tax_rate numeric(6,4) not null default 0.0500 check (tax_rate between 0 and 1),
