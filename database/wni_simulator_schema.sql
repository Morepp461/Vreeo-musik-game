  id bigint generated by default as identity primary key,
  agency_key text not null unique,
  name text not null,
  city text,
  enforcement_power numeric(5,2) not null default 70 check (enforcement_power between 0 and 100),
  investigation_skill numeric(5,2) not null default 70 check (investigation_skill between 0 and 100),
  justice_efficiency numeric(5,2) not null default 70 check (justice_efficiency between 0 and 100),
  corruption_rate numeric(5,4) not null default 0.0500 check (corruption_rate between 0 and 1),
  budget bigint not null default 0,
  updated_at timestamptz not null default now()
);
create table if not exists game_law_profiles (
  character_id bigint primary key references game_ai_characters(id) on delete cascade,
  wanted_level smallint not null default 0 check (wanted_level between 0 and 5),
  convictions integer not null default 0 check (convictions >= 0),
  active_sentence_until timestamptz,
  last_offense_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists game_justice_cases (
  id bigint generated by default as identity primary key,
  crime_event_id bigint not null unique references game_crime_events(id) on delete cascade,
  character_id bigint references game_ai_characters(id) on delete set null,
  status text not null default 'investigating' check (status in ('investigating','arrested','trial','convicted','acquitted','dismissed','served')),
  evidence_score numeric(5,2) not null default 0 check (evidence_score between 0 and 100),
  fine_amount bigint not null default 0 check (fine_amount >= 0),
  sentence_hours integer not null default 0 check (sentence_hours >= 0),
  opened_at timestamptz not null default now(),
  resolved_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);
create table if not exists game_justice_sentences (
  id bigint generated by default as identity primary key,
  case_id bigint not null unique references game_justice_cases(id) on delete cascade,
  character_id bigint references game_ai_characters(id) on delete set null,
  sentence_type text not null default 'penjara' check (sentence_type in ('penjara','denda','penjara_dan_denda')),
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  fine_amount bigint not null default 0 check (fine_amount >= 0),
  status text not null default 'active' check (status in ('active','completed')),
  created_at timestamptz not null default now()
);
create table if not exists game_law_ticks (
  id bigint generated by default as identity primary key,
  tick_key text not null unique,
  tick_at timestamptz not null default now(),
  crimes_opened integer not null default 0,
  investigations_advanced integer not null default 0,
  arrests integer not null default 0,
  trials integer not null default 0,
  convictions integer not null default 0,
  acquittals integer not null default 0,
  sentences_completed integer not null default 0,
  notes text
);
create index if not exists game_justice_cases_status_idx on game_justice_cases(status);
create index if not exists game_justice_cases_character_idx on game_justice_cases(character_id);
create index if not exists game_justice_sentences_status_idx on game_justice_sentences(status);
create index if not exists game_justice_sentences_character_idx on game_justice_sentences(character_id);
